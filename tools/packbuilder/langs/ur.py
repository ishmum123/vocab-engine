    def bind_lexicon(self, lexicon):
        """Hindi-twin entries join the lexicon; the inflection forms (tables and
        rule-built) become form pointers."""
        self._lx = lexicon
        d = self._dict()
        n_twin = 0
        for w, pos, gls, rom, g in d["twin"]:
            ent = {"p": pos, "s": [[gl, "", list(tags), ""] for gl, tags in gls if gl], "ht": set(), "tw": 1}
            if g:
                ent["g"] = g
            if ent["s"]:
                lexicon.E.setdefault(w, []).append(ent)
                n_twin += 1
        for s, lst in sorted(d["forms"].items()):
            cur = lexicon.F.setdefault(s, [])
            for lem, pos in lst:
                if lem != s and [lem, pos, "form"] not in cur:
                    cur.append([lem, pos, "form"])
        for s in list(lexicon.E):
            ents = [e for e in lexicon.E[s] if e["p"] not in SKIP_POS]
            if ents:
                lexicon.E[s] = ents
            else:
                del lexicon.E[s]
        for other, (canon, pos) in sorted(d["alt"].items()):
            moved = [e for e in lexicon.E.get(other, []) if e["p"] == pos]
            if moved and not any(e["p"] == pos and lexicon.entry_usable(e) for e in lexicon.E.get(canon, [])):
                lexicon.E[canon] = [e for e in lexicon.E.get(canon, []) if e["p"] != pos]
                lexicon.F[canon] = [x for x in lexicon.F.get(canon, []) if x[0] != other]
                lexicon.E[canon].extend(
                    {**e, "ht": set(e.get("ht") or ())} for e in moved)
            if other in lexicon.E:
                lexicon.E[other] = [e for e in lexicon.E[other] if e["p"] != pos]
                if not lexicon.E[other]:
                    del lexicon.E[other]
            cur = lexicon.F.setdefault(other, [])
            if [canon, pos, "form"] not in cur:
                cur.append([canon, pos, "form"])
        # entries whose every sense is an inflection label (روپے "oblique/vocative singular",
        # بری "feminine of برا") are forms: a pointer to the lemma, never a word
        form_re = re.compile(r"^(?:direct|oblique|vocative|nominative|plural|singular|feminine|masculine|inflect)"
                             r"|\b(?:feminine|plural|oblique|inflected form) of\b", re.I)
        for w in sorted(lexicon.E):
            ents = lexicon.E[w]
            keep = []
            for e in ents:
                gls = [x[0] for x in e.get("s", []) if x and x[0]]
                if gls and all(form_re.search(g) for g in gls):
                    for lem in self._form_lemmas(w, e["p"], lexicon):
                        cur = lexicon.F.setdefault(w, [])
                        if [lem, e["p"], "form"] not in cur:
                            cur.append([lem, e["p"], "form"])
                    continue
                keep.append(e)
            if keep:
                lexicon.E[w] = keep
            else:
                del lexicon.E[w]
        self._n_twin = n_twin
        self._settle_gender(lexicon)

    def _gender_overrides(self):
        """tools/gender_overrides.txt: "lemma m|f|mf|-" per line (# comments); "mf" is a
        common-gender person noun (میری دوست, میرا دوست), "-" leaves the noun unmarked.
        A lemma the lexicon files under another spelling (پولیس -> پولس) is keyed there."""
        out = {}
        f = self.repo / "tools" / "gender_overrides.txt" if self.repo else None
        if f is not None and f.exists():
            for line in f.read_text(encoding="utf-8").splitlines():
                line = line.split("#", 1)[0].strip()
                if line:
                    w, g = line.rsplit(None, 1)
                    out[fold(w)] = g
        d = self._dict()
        for w in list(out):
            if w not in d["info"]:
                for lem, pos in d["forms"].get(w, []) + ([d["alt"][w]] if w in d["alt"] else []):
                    if pos == "noun":
                        out.setdefault(lem, out[w])
        return out

    def _settle_gender(self, lexicon):
        """Noun gender (QA 2026-09-26): the Urdu head gender and the Hindi twin's gender
        for the same Urdu spelling; agreeing or single-source -> that gender; a
        disagreement -> tools/gender_overrides.txt, else unmarked. An override always
        wins. Stats: build_stats ur_gender."""
        from ..core.util import stat
        hig = self._dict().get("hi_gender", {})
        ov = self._gender_overrides()
        n = Counter()
        mism = []
        for w in sorted(lexicon.E):
            for e in lexicon.E[w]:
                if e.get("p") != "noun":
                    continue
                own = e.get("g") if e.get("g") in ("m", "f") else None
                hi = set(hig.get(w, ()))
                if w in ov:
                    g, why = (ov[w] if ov[w] in ("m", "f", "mf") else None), "override"
                elif w in CLOSED_GENDER:
                    g, why = CLOSED_GENDER[w], "closed_set"
                elif own and (not hi or own in hi):
                    g, why = own, "agree" if hi else "urdu_head"
                elif own:
                    g, why = None, "mismatch"
                    mism.append(f"{w} ur={own} hi={'/'.join(sorted(hi))}")
                elif len(hi) == 1:
                    g, why = next(iter(hi)), "hindi_twin"
                else:
                    g, why = None, "none"
                if g:
                    e["g"] = g
                else:
                    e.pop("g", None)
                n[why] += 1
            # a noun whose pack record comes from another entry of the headword (اردو adj,
            # لاکھ num, شرم intj): that entry carries the noun's gender too
            ng = next((e["g"] for e in lexicon.E[w] if e.get("p") == "noun" and e.get("g")), None)
            if ng:
                for e in lexicon.E[w]:
                    if e.get("p") != "noun":
                        e["g"] = ng
        stat("ur_gender", {"noun_entries": dict(n), "mismatches_unmarked": mism})

    def _noun_of_form(self, w):
        """The noun lemma a surface form belongs to (بچے -> بچہ), or None. Runs at
        tagging time, before the lexicon is bound, so it reads the dictionary forms."""
        if self._has(w, ("noun",)):
            return w
        for lem, pos in self._dict()["forms"].get(w, []):
            if pos == "noun" and self._has(lem, ("noun",)):
                return lem
        return None

    def note_words(self, words):
        """Start of each build_sentences pass: reset the duplicate-text memory
        used by translation_mismatch (build_sentences can run twice)."""
        self._seen_texts = set()
        self._n_dup_text = 0

    def translation_mismatch(self, toks, en):
        """Duplicate after normalisation: two Tatoeba rows (or a Tatoeba row and a
        generated one) whose text is identical once text_norm has run (spelling
        variants, ZWNJ, punctuation) ship once. The first row in corpus order
        keeps its English; later rows are rejected here. Keyed on the token
        surfaces without punctuation, so every later filter (length, links) sees
        the same input for both rows."""
        seen = getattr(self, "_seen_texts", None)
        if seen is None:
            seen = self._seen_texts = set()
        key = " ".join(text_norm(t[0]) for t in toks if t[2] != "PUNCT")
        if key in seen:
            self._n_dup_text = getattr(self, "_n_dup_text", 0) + 1
            return True
        seen.add(key)
        return False

    def surface_link_ok(self, tok):
        """No surface fallback for a name: Urdu has no capitals, so a sentence-initial
        PROPN that spells a pack word (آنا Anna, ماری Mary) is the name, not آنا/مارنا."""
        return tok[2] != "PROPN"

    def _form_lemmas(self, w, pos, lexicon):
        """Lemma candidates of an inflected noun/adjective form: روپے -> روپیہ, بری -> برا."""
        out = []
        for end, reps in (("ے", ("ہ", "ا", "یہ")), ("ی", ("ا",)), ("وں", ("", "ہ", "ا")), ("یں", ("",))):
            if w.endswith(end):
                for r in reps:
                    c = w[:-len(end)] + r
                    if c != w and any(e["p"] == pos and lexicon.entry_usable(e) for e in lexicon.E.get(c, [])):
                        out.append(c)
        return out[:1]

    def post_resolve(self, toks, out):
        """Fixed phrases (compound postpositions, greetings), then light-verb and
        vector compounds. Intentionally unlinked and uncounted (grammar, not
        vocabulary): the progressive رہا/رہی/رہے after a stem, a vector or passive
        جا/گیا/گئی/دیا outside a listed compound, conjunctive کر/کے, and the future
        گا/گی/گے. سکنا and چکنا link. Linking the auxiliaries (as hi does) changes
        corpus counts and sentence selection; it waits for a post-selection link
        hook in core (see urdu TODO.md)."""
        out = list(out)
        f = [t[0] for t in toks]
        n = len(toks)
        # a token the tagger read as a verb with a real infinitive lemma links that verb,
        # never a same-spelled noun/adjective (کھود رہے -> کھودنا, not کھود)
        lx = getattr(self, "_lx", None)
        for i, t in enumerate(toks):
            r = out[i]
            if lx is not None and r and r[1] != "VERB" and t[2] == "VERB" and t[1].endswith("نا") and \
                    t[1] in self._infs() and lx.usable_entries(t[1], self.group_kpos.get("VERB")):
                out[i] = (t[1], "VERB")
        infs = self._infs()
        usable = lambda k: lx is not None and lx.usable_entries(k[0], self.group_kpos.get(k[1]))
        for i, t in enumerate(toks):
            r = out[i]
            nxt = f[i + 1] if i + 1 < n else ""
            # stop-list: آپس never folds to آپ
            if r and f[i] in NEVER_FOLD and r[0] in NEVER_FOLD[f[i]]:
                out[i] = None
                continue
            # an English loan fix_sentence took out of the verb reading (لیٹ "late") never
            # resolves back to the verb through the surface-form table (لیٹنا)
            if r and r[1] == "VERB" and f[i] in LOAN_EN and toks[i][2] in ("ADJ", "NOUN"):
                out[i] = None
                continue
            # echo second half of a jingle compound (ملتا جلتا "similar"): no verb of its own
            if r and i and f[i] in ECHO_AFTER and fold(toks[i - 1][0]) in ECHO_AFTER[f[i]]:
                out[i] = None
                continue
            if r and i + 1 < n and f[i + 1] in ECHO_AFTER and f[i] in ECHO_AFTER[f[i + 1]]:
                out[i] = None       # ملتے جلتے "alike": not ملنا "to meet"
                continue
            # a feminine noun with an entry of its own never folds to the masculine
            # (نانی != نانا, دادی, چچی, لڑکی)
            if r and r[1] == "NOUN" and f[i].endswith("ی") and r[0] == f[i][:-1] + "ا" and usable((f[i], "NOUN")):
                out[i] = r = (f[i], "NOUN")
            # perfect participle vs causative stem: X-ا before a copula or ہوا, or closing
            # the clause, is the perfect of X-نا (سنا ہے: سننا, بنا ہے: بننا), not X-انا
            if r and r[1] == "VERB" and r[0] == f[i] + "نا" and f[i].endswith("ا") and \
                    f[i][:-1] + "نا" in infs and usable((f[i][:-1] + "نا", "VERB")) and \
                    (nxt in self.COPULA or nxt in ("ہوا", "ہوئی", "ہوئے", "", "۔", "؟", "!", "،") or
                     nxt in ("تو", "اور", "لیکن", "مگر", "کہ", "پھر") or     # جب پانی اترا تو ...
                     # stative continuative: پھنسا رہا۔ "remained stuck" (no auxiliary after رہا,
                     # unlike the progressive پکا رہی ہے)
                     (nxt in ("رہا", "رہی", "رہے") and (i + 2 >= n or f[i + 2] in ("", "۔", "؟", "!", "،")))):
                out[i] = r = (f[i][:-1] + "نا", "VERB")
            # stative participle + ہوا (تھکا ہوا "tired", بھری ہوئی): the participle adjective
            if r and r[1] == "VERB" and nxt in ("ہوا", "ہوئی", "ہوئے") and f[i][-1:] in ("ا", "ی", "ے"):
                k = (f[i][:-1] + "ا", "ADJ")
                if usable(k):
                    out[i] = k
            # سو/دو read as numbers in verb position: سو رہا (sleeping), لگا دو (give)
            elif r and r[1] == "NUM" and f[i] == "سو" and nxt[:3] in ("رہا", "رہی", "رہے", "گیا", "گئی", "گئے", "جاو", "جات", "جائ"):
                out[i] = ("سونا", "VERB")
            elif r and r[1] == "NUM" and f[i] == "دو" and i > 0 and \
                    (f[i - 1] + "نا" in infs or (out[i - 1] and out[i - 1][1] == "VERB")) and nxt in ("", "۔", "!", "؟"):
                out[i] = ("دینا", "VERB")
            # a bare verb stem the tagger read as a noun before a vector verb (جیت لیا)
            r = out[i]
            if r and r[1] != "VERB" and i + 1 < n and out[i + 1] and out[i + 1][1] == "VERB" and \
                    out[i + 1][0] in VECTORS and f[i] + "نا" in infs and usable((f[i] + "نا", "VERB")):
                out[i] = (f[i] + "نا", "VERB")
            # a bare stem the tagger read as a noun before the progressive or کر (ہنس رہی, ہنس کر)
            r = out[i]
            if r and r[1] not in ("VERB", "NUM") and nxt in ("رہا", "رہی", "رہے", "رہیں", "کر", "کے") and \
                    toks[i][2] != "PROPN" and f[i] + "نا" in infs and usable((f[i] + "نا", "VERB")) and \
                    not (nxt == "کے" and (self._has(f[i], ("noun", "adj", "pron")) or
                                         i + 2 < n and f[i + 2] in ("لیے", "بعد", "ساتھ", "پاس", "بارے"))):
                # کے after a dictionary noun is the genitive (سال کے, not سالنا)
                out[i] = (f[i] + "نا", "VERB")
        # پتہ نہیں / معلوم نہیں ("(I) don't know"): the light verb, with the copula left out
        for i in range(n - 1):
            if f[i] in ("پتہ", "پتا", "معلوم") and f[i + 1] == "نہیں" and (i + 2 >= n or toks[i + 2][2] == "PUNCT" or
                                                                       f[i + 2] not in self.COPULA):
                k = ("پتہ ہونا" if f[i] != "معلوم" else "معلوم ہونا", "VERB")
                if usable(k) or k[0] in LIGHT_VERBS:
                    out[i] = k
        # اسی لیے / اسی لئے: the conjunction اس لیے
        for i in range(n - 1):
            if f[i] == "اسی" and f[i + 1] == "لیے" and usable(("اس لیے", "CONJ")):
                out[i] = out[i + 1] = ("اس لیے", "CONJ")
        # fixed multi-token phrases (longest first)
        taken = set()
        # an inflecting (DET/ADJ) phrase matches its -ی/-ے forms too (کون سی, کون سے -> کون سا)
        infl = lambda a, b, g: a == b or (g in ("DET", "ADJ") and b.endswith("ا") and a in (b[:-1] + "ی", b[:-1] + "ے"))
        for parts, key in PHRASE_TOKS:
            L = len(parts)
            for i in range(n - L + 1):
                if all(infl(a, b, PHRASES[key][0]) for a, b in zip(f[i:i + L], parts)) and \
                        not taken & set(range(i, i + L)):
                    grp = PHRASES[key][0]
                    for j in range(i, i + L):
                        out[j] = (key, grp)
                        taken.add(j)
        # possessive + compound postposition (میرے پاس, میری طرف, اپنے ساتھ): the possessive
        # carries the کے/کی, the rest links the postposition
        for parts, key in PHRASE_TOKS:
            if PHRASES[key][0] != "ADP" or parts[0] not in ("کے", "کی") or len(parts) < 2:
                continue
            rest, L = parts[1:], len(parts) - 1
            for i in range(1, n - L + 1):
                if tuple(f[i:i + L]) == rest and not taken & set(range(i, i + L)) and \
                        f[i - 1] in POSS_OBL[parts[0]]:
                    for j in range(i, i + L):
                        out[j] = (key, "ADP")
                        taken.add(j)
        for i in range(n):
            r = out[i]
            if i in taken or not r or r[1] != "VERB":
                continue
            prev = i - 1
            pr = out[prev] if prev >= 0 else None
            ptok = toks[prev] if prev >= 0 else None
            # گرا دیا / لگا دو: before دینا/ڈالنا/لینا the token is the bare stem of its own
            # infinitive (گرانا), not a perfective of گرنا
            if r[0] in ("دینا", "ڈالنا", "لینا") and pr and pr[1] == "VERB" and prev not in taken and \
                    ptok[0] + "نا" != pr[0] and ptok[0] + "نا" in self._infs() and \
                    lx is not None and lx.usable_entries(ptok[0] + "نا", self.group_kpos.get("VERB")):
                out[prev] = pr = (ptok[0] + "نا", "VERB")
            # stem + vector verb (کر دیا, آ گیا, چلا گیا)
            if r[0] in VECTORS and pr and pr[1] == "VERB" and prev not in taken and \
                    (ptok[0] + "نا" == pr[0] or (pr[0] == "چلنا" and ptok[0] in ("چلا", "چلی", "چلے"))):
                stem_key = ptok[0] if ptok[0] + "نا" == pr[0] else "چلا"
                # noun + light-verb stem + vector (معاف کر دیا): the light verb wins, the vector is grammar
                jj = prev - 1
                if jj >= 0 and jj not in taken and toks[jj][2] not in ("PUNCT", "PROPN"):
                    lvn = LV_INDEX.get(pr[0], {})
                    lv = lvn.get(f[jj]) or (lvn.get(out[jj][0]) if out[jj] else None)
                    if lv:
                        out[jj] = out[prev] = (lv, "VERB")
                        out[i] = None
                        taken |= {i, prev, jj}
                        continue
                comp = LV_INDEX.get(r[0], {}).get(stem_key)
                if comp:
                    out[i] = out[prev] = (comp, "VERB")
                    taken |= {i, prev}
                else:
                    out[i] = None            # vector verb: grammar
                continue
            if r[0] == "رہنا" and pr and pr[1] == "VERB" and (
                    ptok[0] + "نا" == pr[0] or re.search("(تا|تی|تے)$", ptok[0])):
                out[i] = None                # progressive کر رہا ہے, continuative کرتا رہتا ہے
                continue
            if f[i] in ("کر", "کے") and prev >= 0 and (ptok[0] + "نا" in self._infs() or
                                                     (ptok[0].endswith("ے") and ptok[0][:-1] + "ینا" in self._infs())):
                out[i] = None                # conjunctive participle: کھا کر, چیخ چیخ کے
                continue
            if r[0] == "جانا" and pr and pr[1] == "VERB" and ptok[0] != pr[0][:-2] and \
                    ptok[0].endswith(("ا", "ی", "ے", "یا")) and toks[prev][2] in ("VERB", "AUX"):
                out[i] = None                # passive: کیا جاتا ہے
                continue
        for i in range(1, n):
            # کیا after a copula at the end of a clause asks a question (ہو رہی ہے کیا؟)
            if f[i] == "کیا" and toks[i - 1][1] == "ہونا" and toks[i - 1][2] == "AUX" and \
                    (i + 1 >= n or toks[i + 1][2] == "PUNCT"):
                out[i] = ("کیا", "PRON")
        # noun/adjective + light verb (particles and one adverb may stand between)
        for i in range(n):
            r = out[i]
            if i in taken or not r or r[1] != "VERB" or r[0] not in LV_INDEX:
                continue
            nouns = LV_INDEX[r[0]]
            j = i - 1
            skipped = 0
            while j >= 0 and j not in taken and toks[j][0] in ("نہیں", "نہ", "بھی", "ہی", "تو", "مت") and skipped < 2:
                j -= 1
                skipped += 1
            if j < 0 or j in taken:
                continue
            key = f[j]
            base = out[j][0] if out[j] else key
            comp = nouns.get(key) or nouns.get(base)
            if not comp and j >= 1:
                comp2 = nouns.get(f[j - 1] + " " + key)
                if comp2 and j - 1 not in taken:
                    out[j - 1] = (comp2, "VERB")
                    taken.add(j - 1)
                    comp = comp2
            if comp and comp.endswith(" ہونا") and j >= 1 and toks[j - 1][2] == "ADJ" and \
                    (j - 1) not in taken:
                comp = None                  # مستقل پتہ ہے: "the permanent address is", not "know"
            if comp and toks[j][2] not in ("PUNCT", "PROPN"):
                out[i] = out[j] = (comp, "VERB")
                taken |= {i, j}
        return out

