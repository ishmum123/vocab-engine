# ---- romanisation: one scheme for kaikki, Hindi-twin and manual prons -----------
# Long vowels ā ī ū e o ai au, short a i u; retroflex ṭ ḍ ṛ (the only dotted
# consonants); aspirates bh ph th ṭh ch kh gh ...; c چ, x خ, ġ غ, ś ش, ž ژ; ʿ for ع
# (always written); ʾ for hamza after a consonant (jurʾat, masʾala; one glyph, never ASCII ');
# ̃ for nasal (mẽ, nahī̃). A written word ending in consonant + ی ends in -ī (axlāqī).
# One pron word per written word (zyāda tar, zimme dārī).
# Word-final ہ after a consonant is -a (kamra, dobāra); after a long vowel, in a
# monosyllable, or in PRON_KEEP_H it is -h (rāh, dah, jagah). Izafat is -e
# (barāh-e karam). Other Arabic-letter dots (ḥ ṣ ẓ t̤) are dropped.
