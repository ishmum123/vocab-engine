def _compose(s):
    for a, b in COMPOSE:
        if a in s:
            s = s.replace(a, b)
    return s


def display_norm(s):
    """Display spelling: Urdu codepoints (ی ک ہ), hamza forms composed, ۓ as ئے,
    harakat stripped (tanwin fath and superscript alef kept: فوراً, اعلیٰ)."""
    if not s:
        return s
    s = DISPLAY_MARKS_RE.sub("", _compose(s).translate(CHAR_MAP)).replace("ۓ", "ئے")
    return s.strip()


def _fold1(w):
    w = MARKS_RE.sub("", w).replace(ZWNJ, "").translate(FOLD_MAP)
    return YE_SPELLING.get(w, w)


def fold(s):
    """Matching spelling: display_norm, then every mark and ZWNJ dropped, ۂ ->
    ہ, ؤ -> و, أ -> ا, and hamza/ye spelling variants of one word merged."""
    if not s:
        return s
    s = display_norm(s)
    if " " in s:
        return " ".join(_fold1(p) for p in s.split(" ") if p)
    return _fold1(s)


