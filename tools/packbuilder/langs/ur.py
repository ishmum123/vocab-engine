_YE_WORD_RE = re.compile("[" + LET + "]+")
# unrepairable: Latin letters/ASCII digits, Arabic-block letters Urdu does not
# write (أ for ا, Uyghur/Arabic-only letters), a slash or bracket (alternatives
# or glosses in the text), a year used as a century, a doubled postposition
# (کے متعلق میں), گم without ہونا (گم گیا)
URDU_LETTERS = "آابپتٹثجچحخدڈذرڑزژسشصضطظعغفقکگلمنںوہھءیےئؤۂ"
# agreement slips no reading makes right: first person future without ں (جاؤ گا),
# 3sg subjunctive with plural گے (کرے گے), plural participle with ہے (کھاتے ہے),
# feminine plural participle/progressive with ہیں (رہتیں ہیں, رہیں ہیں)
TEXT_DROP_RE = re.compile(_WB + "(?!ہو\\s)[" + LET + "]*[وؤ]\\s+(?:گا|گی)" + _WE + "|[" + LET + "]ے\\s+گے" + _WE + "|"
                          "تے\\s+ہے" + _WE + "|(?:تیں|رہیں)\\s+ہیں" + _WE + "|"
                          "[A-Za-z0-9/()\\[\\]]|(?![" + URDU_LETTERS + "])[ء-يٱ-ۓ]|[۰-۹٠-٩]{3,}\\s*صدی|متعلق\\s+میں" + _WE + "|" +
                          _WB + "گم\\s+(?:گیا|گئی|گئے|گئیں)" + _WE)


def text_norm(s):
    """display_norm plus the spelling-slip repairs above (sentence text only)."""
    if not s:
        return s
    s = display_norm(INVISIBLE_RE.sub("", s))
    for rx, rep in TEXT_FIXES:
        s = rx.sub(rep, s)
    s = _YE_WORD_RE.sub(lambda m: YE_SPELLING.get(m.group(0), m.group(0)), s)
    return s.strip()


