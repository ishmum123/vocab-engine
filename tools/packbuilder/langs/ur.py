def _syllables(t):
    return len(re.findall(r"[aāiīuūeo]+", t))


def _is_vowel(c):
    import unicodedata
    return c in "ʿʾ'̃" or unicodedata.normalize("NFD", c)[0] in "aiueo"


def _lead_cons(t):
    """Consonant letters before t's first vowel, an aspirate h counting with its consonant."""
    n, i = 0, 0
    while i < len(t) and not _is_vowel(t[i]):
        if t[i] == "h" and i and t[i - 1] in _ASP:
            i += 1
            continue
        n, i = n + 1, i + 1
    return n, i


def pron_norm(word, p, pos=None):
    """Map any source romanisation onto the pack scheme above (idempotent)."""
    if not p:
        return p
    import unicodedata
    for k in ((word, pos), (word, None)):
        if k in PRON_WORD:
            return PRON_WORD[k]
    p = unicodedata.normalize("NFC", p.lower())
    for a, b in _PRON_CHARS:
        p = p.replace(a, b)
    p = p.replace("ŏ", "ā" if re.search("[اآ]", word) else "o")
    if "ش" in word and "سہ" not in word:
        p = p.replace("sh", "ś")
    if "خ" in word and "کھ" not in word:
        p = p.replace("kh", "x")
    if "غ" in word and "گھ" not in word:
        p = p.replace("gh", "ġ")
    if "ع" in word and not re.search("[ئءأ]", word):
        p = p.replace("ʾ", "ʿ")
    ut, pt = word.split(), p.split()
    if len(ut) == 1 and len(pt) > 1:
        pt = ["".join(pt)]                     # اداکاری: one written word, one pron word
    if len(ut) != len(pt):
        return p
    out = []
    for u, t in zip(ut, pt):
        if u in PRON_TOKEN:
            out.append(PRON_TOKEN[u])
            continue
        t = re.sub(r"-i$", "-e", t)
        if len(u) > 1 and u.endswith("ی") and u[-2] not in "اوی" and re.search(r"[^aāiīuūeoy]i$", t):
            t = t[:-1] + "ī"          # اخلاقی axlāqī, کارکردگی kārkardagī
        if u.startswith("ع") and t[:1] in "aāiīuūeo":
            t = "ʿ" + t
        if u.endswith("ع") and len(u) > 1 and u[-2] not in "اوی" and t.endswith("ā"):
            t = t[:-1] + "aʿ"
        if u.endswith("ہ") and len(u) > 1 and u[-2] != "ا" and u not in PRON_KEEP_H:
            if t.endswith("ā"):
                t = t[:-1] + "a"
            elif re.search(r"[^āīūeo]ah$", t) and _syllables(t) >= 2:
                t = t[:-1]
        # ā only where the spelling has an alif: خرابی is xarābī (no alif after خ)
        if u[:1] not in "اآع":
            n, i = _lead_cons(t)
            j = 0
            for _ in range(n):
                j += 1
                if j < len(u) and u[j] == "ھ":
                    j += 1
            if t[i:i + 1] == "ā" and j < len(u) and u[j] not in "اآوی":
                t = t[:i] + "a" + t[i + 1:]
        # retroflex / aspirate marks the spelling demands (توڑنا toṛnā, بڑھنا baṛhnā)
        for ch, r, plain, other in (("ڑ", "ṛ", "r", "ر"), ("ٹ", "ṭ", "t", "تطة"), ("ڈ", "ḍ", "d", "دذ")):
            if ch in u and r not in t and not any(o in u for o in other):
                t = t.replace(plain, r)
        for ch, r in (("ڑھ", "ṛ"), ("ٹھ", "ṭ"), ("ڈھ", "ḍ")):
            if ch in u and r in t and r + "h" not in t:
                t = t.replace(r, r + "h", 1)
        out.append(t)
    return " ".join(out)



