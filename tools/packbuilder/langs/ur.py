    # ---- finishing ----------------------------------------------------------------------
    def finalize_words(self, env, ctx, words):
        from collections import Counter
        from ..core.gloss import strip_gloss_style
        from ..core.util import stat
        info = self._dict()["info"]
        spell = {}
        for r in ctx["rows_by_sid"].values():
            for m in self.word_re.finditer(text_norm(r[1])):
                w = m.group(0).strip(ZWNJ)
                spell.setdefault(fold(w), Counter())[w] += 1

        def display(key):
            parts = []
            for p in key.split(" "):
                c = spell.get(p)
                best = sorted(c.items(), key=lambda kv: (-kv[1], kv[0] != p, kv[0]))[0][0] if c else p
                parts.append(best)
            return " ".join(parts)

        # headword spelling = the corpus majority among its spelling variants (QA 2026-09-26:
        # پولس -> پولیس, گندہ -> گندا, بھارا -> بھاری): a dictionary alternative form, a form
        # pointer that only adds/drops a medial ی/و/ا, or, for an -ا adjective never seen
        # with -ا/-ے, the invariable -ی headword. Only a strictly commoner spelling wins.
        d = self._dict()
        alt_of = {}
        for other, (canon, pos_) in d["alt"].items():
            alt_of.setdefault((canon, pos_), []).append(other)
        for s_, lst in d["forms"].items():
            for lem, pos_ in lst:
                if lem != s_ and len(s_) == len(lem) + 1 and s_[0] == lem[0] and s_[-1] == lem[-1] and \
                        any(s_[:k] + s_[k + 1:] == lem and s_[k] in "یوا" for k in range(1, len(s_) - 1)):
                    alt_of.setdefault((lem, pos_), []).append(s_)
        n_tok = lambda x: sum(spell.get(fold(x), {}).values())
        respelt = []

        def canonical(key, pos_):
            if " " in key:
                return key
            cands = list(alt_of.get((key, pos_), []))
            if pos_ == "adj" and key.endswith("ا") and n_tok(key) + n_tok(key[:-1] + "ے") == 0 and \
                    any(r[1] == "adj" and r[5] == "ur" and r[6] for r in info.get(key[:-1] + "ی", [])):
                cands.append(key[:-1] + "ی")
            best = max(cands, key=lambda x: (n_tok(x), x), default=None)
            if best and n_tok(best) > n_tok(key):
                respelt.append(f"{key} -> {best} ({n_tok(key)} vs {n_tok(best)} corpus tokens)")
                return best
            return key

        def rom(key, pos=None, en=None):
            if key in FIXED_PRON:
                return FIXED_PRON[key]
            rows = info.get(key, [])
            cands = [r for r in rows if r[2] and r[6] and (pos is None or r[1] == pos)] or \
                    [r for r in rows if r[2] and r[6]] or [r for r in rows if r[2]]
            if en and len(cands) > 1:
                ours = set(re.findall(r"[a-z]{3,}", en.lower()))
                cands = sorted(cands, key=lambda r: (r[5] != "ur", -len(ours & set(re.findall(r"[a-z]{3,}", (r[4] or "").lower())))))
            return _ROM_TRIM.sub("", cands[0][2]).strip().lower() if cands else None

        def part_rom(x):
            """A compound's part: its own romanisation, else a verb stem or stem + -ا/-ی/-ے
            from the infinitive (بھیج, چلا: bhej, calā), else the -ی/-ے form of an -ا word
            (کے, دوسرے: ke, dūsre)."""
            r = rom(x)
            if r:
                return r
            for end, v in (("", ""), ("ا", "ā"), ("ی", "ī"), ("ے", "e")):
                st = x[:-len(end)] if end else x
                if (not end or x.endswith(end)) and st:
                    ri = rom(st + "نا", "verb")
                    if ri and ri.endswith("nā"):
                        return ri[:-2] + v
            if x.endswith("ے"):
                ri = rom(x[:-1] + "ینا", "verb")                # دے, لے: stems of دینا, لینا
                if ri and ri.endswith("nā"):
                    return ri[:-2]
            if x[-1:] in ("ی", "ے"):
                for base in (x[:-1] + "ا", x[:-1] + "ہ"):
                    rb = rom(base)
                    if rb and rb[-1:] in ("ā", "a"):
                        return rb[:-1] + ("ī" if x[-1] == "ی" else "e")
            return None

        no_pron, twin_gloss = [], []
        n_strip = 0
        for w in words:
            w["en"] = strip_gloss_style(w["en"])
            # a gender mark belongs to nouns only: a word the builder read as a noun and
            # POS_LABEL relabelled (اوہ intj, فضول adj, ادھر adv) loses it
            if w["pos"] != "noun" and re.search(r" \((?:m|f|m/f)\)$", w["en"]):
                w["en"] = re.sub(r" \((?:m|f|m/f)\)$", "", w["en"])
                w.pop("_gender", None)
                n_strip += 1
            w["en"] = re.sub(r"[,;]\s*(including|such as|e\.g\.|namely|like|especially|of|and|or)\s*$", "", w["en"])
            pos = {"prep": "postp"}.get(w["pos"], w["pos"])
            orig = w["lemma"]
            key = canonical(orig, pos)
            w["w"] = w["lemma"] = display(key)
            p = rom(key, pos, w["en"]) or rom(orig, pos, w["en"])
            if p is None and " " in key:
                ps = [part_rom(x) for x in key.split(" ")]
                p = " ".join(ps) if all(ps) else None
            p = pron_norm(key, p, w["pos"])
            if p and " " in key and len(p.split()) != len(key.split()):
                ps = [part_rom(x) for x in key.split(" ")]
                if all(ps):
                    p = pron_norm(key, " ".join(ps), w["pos"])
            if p:
                w["pron"] = p
            else:
                no_pron.append(key)
            rows = info.get(key, [])
            if rows and not any(r[5] == "ur" and r[6] for r in rows) and any(r[5] == "hi" for r in rows):
                twin_gloss.append(key)
            w.pop("alt", None)
        stat("ur_display", {"gender_marks_stripped_from_non_nouns": n_strip,
                            "duplicate_texts_after_normalisation": getattr(self, "_n_dup_text", 0),
                            "gen_english_paren_tags_stripped": getattr(self, "_n_en_paren", 0),
                            "headwords_respelt_by_corpus_majority": respelt,
                            "words_without_pron": sorted(no_pron),
                            "pron_coverage": f"{len(words) - len(no_pron)}/{len(words)}",
                            "hindi_twin_entries_in_lexicon": getattr(self, "_n_twin", 0),
                            "words_glossed_via_hindi_twin": len(twin_gloss),
                            "words_glossed_via_hindi_twin_list": sorted(twin_gloss)})

    # ---- checks ----------------------------------------------------------------------
    def check_word(self, w):
        f = fold(w["w"])
        last = f.split(" ")[-1]
        if w.get("pos") == "verb" and not (last.endswith("نا") or f == "چاہیے"):
            return f"verb {w['id']} {w['w']!r}: not an infinitive"
        info = self._dict()["info"]
        if w.get("pos") == "noun" and " " not in f and (f.endswith("وں") or f.endswith("یں")) and \
                any(r[1] == "noun" for r in info.get(f[:-2], [])) and \
                not any(r[1] == "noun" and r[6] for r in info.get(f, [])):    # پاؤں is a headword
            return f"noun {w['id']} {w['w']!r}: plural/oblique form as a lemma"
        if re.search("[يكهَ-ْ]", w["w"]):
            return f"word {w['id']} {w['w']!r}: Arabic yeh/kaf/heh or harakat in w"
        return None

