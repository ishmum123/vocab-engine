def _lev(a, b):
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


def _spelling_alts(info, forms, pairs):
    """{non-canonical spelling: canonical spelling} for Wiktionary "alternative form of"
    pairs that are spelling variants of one word (single words, edit distance <= 2, the
    variant has no senses of its own under that POS). The canonical spelling is the one
    used more (wordfreq ur); it takes the senses of the other when it has none."""
    from wordfreq import zipf_frequency
    alt = {}
    for w, t, pos in pairs:
        if not w or not t or w == t or " " in w or " " in t or _lev(w, t) > 2 or min(len(w), len(t)) < 2 or \
                (min(len(w), len(t)) < 3 and _lev(w, t) > 1):
            continue
        if any(r[6] for r in info.get(w, [])) or _lev(w, t) > (1 if min(len(w), len(t)) < 5 else 2):
            continue
        if any(lem not in (w, t) for lem, _ in forms.get(w, [])):
            continue                                    # also an inflected form of another word
        rows = [r for r in info.get(t, []) if r[1] == pos and r[6]]
        if not rows:
            continue
        canon, other = (w, t) if zipf_frequency(w, "ur") > zipf_frequency(t, "ur") else (t, w)
        if canon == w:
            for r in rows:
                info.setdefault(w, []).append([r[0], r[1], r[2], r[3], r[4], r[5], True])
        alt[other] = [canon, pos]
    return dict(sorted(alt.items()))


_GLOSS_STOP = {"a", "an", "the", "of", "to", "or", "and", "in", "on", "for", "one", "be"}


def _gloss_words(rows):
    return {w for r in rows for w in re.findall(r"[a-z]+", (r[4] or "").lower())} - _GLOSS_STOP


def _dup_spellings(info, forms):
    """Two headwords that are one word in two spellings, both with senses:
    final ا/ہ (ڈراما/ڈرامہ, بھروسا/بھروسہ) and a prothetic ا before s+consonant
    (اسٹیشن/سٹیشن). Same POS and a shared gloss word; the more used spelling is
    canonical, the other becomes a spelling variant."""
    from wordfreq import zipf_frequency
    alt = {}
    for w in sorted(info):
        cands = []
        if len(w) >= 3 and w.endswith("ا"):
            cands.append(w[:-1] + "ہ")
        if len(w) >= 4 and w.startswith("اس") and w[2] not in "اوی":
            cands.append(w[1:])
        for t in cands:
            if t not in info:
                continue
            for pos in ("noun", "adj"):
                a = [r for r in info[w] if r[1] == pos and r[6]]
                b = [r for r in info[t] if r[1] == pos and r[6]]
                if not a or not b or not (_gloss_words(a) & _gloss_words(b)):
                    continue
                if any(lem not in (w, t) for lem, _ in forms.get(w, []) + forms.get(t, [])):
                    continue
                canon, other = (w, t) if zipf_frequency(w, "ur") >= zipf_frequency(t, "ur") else (t, w)
                alt.setdefault(other, [canon, pos])
    return alt


def _gender(d):
    for h in d.get("head_templates", []):
        a = h.get("args", {})
        g = str(a.get("1", "") or a.get("g", ""))
        if g[:1] in ("m", "f"):
            return g[:1]
    for f in d.get("forms", []):
        t = set(f.get("tags") or [])
        if "canonical" in t and t & {"masculine", "feminine"}:
            return "m" if "masculine" in t else "f"
    return None


