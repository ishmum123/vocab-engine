    def _verb_lemma(self, surface, lemma):
        infs = self._infs()
        if surface in self.COPULA:
            return "ہونا"
        if lemma in infs:
            # Stanza's lemma is a real infinitive; keep it when the surface is one of its forms
            cands = self._forms_of(surface, ("verb",))
            if not cands or lemma in cands:
                return lemma
            return self._pick_verb(cands, lemma)
        cands = [c for c in self._forms_of(surface, ("verb",)) if c in infs]
        if cands:
            return self._pick_verb(cands, lemma)
        if surface + "نا" in infs:
            return surface + "نا"                       # a bare stem
        if surface.endswith("ہ") and surface[:-1] + "نا" in infs:
            return surface[:-1] + "نا"                  # کہہ, رہ: stems written with a final ہ
        if "ئ" in surface[1:]:
            c = surface[:surface.index("ئ", 1)] + "ینا"         # پئیں, جئے -> پینا, جینا
            if c in infs:
                return c
        if lemma.endswith("ےنا") and lemma[:-3] + "ینا" in infs:
            return lemma[:-3] + "ینا"                   # Stanza دےنا/لےنا
        for end in ("تا", "تی", "تے", "تیں", "نے", "نی", "یں", "وں", "ا", "ی", "ے", "و"):
            if surface.endswith(end) and surface[:-len(end)] + "نا" in infs:
                return surface[:-len(end)] + "نا"
        return lemma

    @staticmethod
    def _kp(upos):
        return {"NOUN": "noun", "ADJ": "adj", "ADV": "adv"}[upos]

    @staticmethod
    def _verbless_clause(toks, i):
        """Tokens before i back to the clause start (punctuation or conjunction) number
        two or more and hold no finite verb (conjunctive stems before کر/کے, کر/کے
        themselves and infinitives do not count)."""
        j = i - 1
        while j >= 0 and toks[j][2] not in ("PUNCT", "CCONJ", "SCONJ"):
            j -= 1
        clause = range(j + 1, i)
        return len(clause) >= 2 and not any(
            toks[k][2] in ("VERB", "AUX") and not toks[k][0].endswith(("نا", "نے", "نی")) and
            toks[k][0] not in ("کر", "کے") and not (k + 1 < len(toks) and toks[k + 1][0] in ("کر", "کے"))
            for k in clause)

    def _has(self, w, poses):
        return any(r[1] in poses and r[6] for r in self._dict()["info"].get(w, []))

    passage_retag_names = True

    def passage_retag(self, toks, names=frozenset()):
        """Passages: a token spelled like a declared name (source "names") is that name
        (Urdu has no capitals to mark them): فرح, not فرحنا; کامران, not کامر."""
        fn = {fold(n) for n in names}
        prev = False
        for t in toks:
            if fold(t[0]) in fn:
                t[1], t[2] = t[0], "PROPN"
                # core hands names over split into words: a declared word right after another
                # that is also a common word (آباد, روڈ) is the tail of a multi-word name
                # (اسلام آباد), uncounted and never a pack word; فرح لاہور stays two names
                tail = prev and (t[0] in PLACE_TAILS or self._has(fold(t[0]), ("noun", "adj", "verb", "adv")))
                t[3] = "NameTail=Yes" if tail else "NameDecl=Yes"
                prev = True
            else:
                prev = False
        return toks

    @property
    def passage_lemma_alias(self):
        """A listed compound that is not a pack word links its head in a passage: a
        vector compound its main verb (سن لینا -> سننا, ڈر جانا -> ڈرنا), a light verb
        its noun (یاد کرنا -> یاد, پتہ چلنا -> پتہ)."""
        out = {}
        for comp in LIGHT_VERBS:
            parts = comp.split()
            head = " ".join(parts[:-1])
            out[comp] = head + "نا" if parts[-1] in VECTORS and len(parts) == 2 and not head.endswith("نا") else head
        return out

    def _noun_base(self, w, has):
        """The direct singular of an inflected masculine noun form: -ے/-وں of an -ہ/-ا
        noun (عملے عملوں -> عملہ, تالے -> تالا); None when no such noun exists."""
        c = [n for n in self._forms_of(w, ("noun",)) if has(n, ("noun",)) and n != w]
        if c:
            return c[0]                                     # روپے -> روپیہ (inflection table)
        if w.endswith("ائے") and has(w[:-2] + "یہ", ("noun",)):
            return w[:-2] + "یہ"                            # کرائے -> کرایہ
        if w.endswith("ے") and has(w[:-1] + "یہ", ("noun",)):
            return w[:-1] + "یہ"                            # روپے -> روپیہ
        for end in ("ے", "وں"):
            if w.endswith(end) and len(w) > len(end) + 1:
                for r in ("ہ", "ا"):
                    c = w[:-len(end)] + r
                    if has(c, ("noun",)):
                        return c
        return None

    def _pick_verb(self, cands, lemma):
        if len(cands) == 1:
            return cands[0]
        from wordfreq import zipf_frequency
        # the Stanza lemma's stem decides (دےنا -> دینا), then frequency
        stem = lemma[:-2] if lemma.endswith("نا") else lemma
        near = [c for c in cands if c[:-2] == stem or c.startswith(stem)]
        pool = near or cands
        return sorted(pool, key=lambda c: (-zipf_frequency(c, "ur"), c))[0]

    def fix_token(self, tok):
        text, lemma, upos, ms = tok
        ftext, flemma = fold(text), fold(lemma)
        if upos != "PUNCT":
            ftext, flemma = ftext.strip(TOKEN_PUNCT) or ftext, flemma.strip(TOKEN_PUNCT) or flemma
        info = self._dict()["info"]
        has = lambda w, poses: any(r[1] in poses and r[6] for r in info.get(w, []))
        if ftext in self.FUTURE and upos in ("AUX", "VERB", "PART", "NOUN", "ADP"):
            return [ftext, ftext, "X", ms]                   # future marker, never گانا "to sing"
        if ftext in NAMES and ftext not in NAME_EN:
            return [ftext, ftext, "PROPN", ms]
        if ftext in PRON_FORMS and upos in ("PRON", "DET", "ADJ", "NOUN", "ADV", "PROPN", "X"):
            upos = "DET" if PRON_FORMS[ftext] in POSSESSIVES else "PRON"
            return [ftext, PRON_FORMS[ftext], upos, ms]
        if ftext in POSSESSIVES:
            return [ftext, ftext, "DET", ms]
        if ftext in ("کا", "کی", "کے") and upos in ("ADP", "PART", "ADJ", "NOUN", "PRON"):
            return [ftext, "کا", "ADP", ms]
        if re.fullmatch("چاہ(?:ی|ئ|ئی|یئ)(?:ے|یں|ں)", ftext) and upos in ("AUX", "VERB", "NOUN", "ADJ"):
            return [ftext, "چاہیے", "VERB", ms]             # the modal "should, need", not چاہنا "want"
        if ftext == "دونوں":
            return [ftext, "دونوں", "PRON", ms]             # "both", never the numeral دو
        if ftext == "آپس":
            return [ftext, "آپس", "PRON", ms]               # آپس میں "among themselves", never آپ "you"
        if upos == "NOUN" and ftext.endswith("ی") and flemma == ftext[:-1] + "ا" and has(ftext, ("noun",)):
            return [ftext, ftext, "NOUN", ms]               # نانی is a word, not a form of نانا
        if ftext == "نا" and upos == "PUNCT":
            return [ftext, "نا", "PART", ms]                # tag question "ہے نا؟", not punctuation
        if ftext in self.COPULA and upos in ("AUX", "VERB"):
            return [ftext, "ہونا", "AUX", ms]
        if ftext in self.UPOS_FIX and upos in ("ADJ", "NOUN", "ADV", "ADP", "PRON", "DET", "SCONJ", "CCONJ", "PART"):
            upos, flemma = self.UPOS_FIX[ftext], ftext      # the surface decides first (کیسے "how", not کیسا)
        elif flemma in self.UPOS_FIX and upos in ("ADJ", "NOUN", "ADV", "ADP", "PRON", "DET", "SCONJ", "CCONJ", "PART"):
            upos = self.UPOS_FIX[flemma]
        if upos in ("NOUN", "ADJ", "ADV") and flemma != ftext and len(flemma) > 1 and \
                not ftext.startswith(flemma[:max(1, len(flemma) - 1)]):
            # Stanza's lemma is no stem of the surface (اوپر -> پر): the dictionary word
            for kp, g in (("adv", "ADV"), ("noun", "NOUN"), ("adj", "ADJ")):
                if has(ftext, (kp,)) and (g == upos or not has(ftext, (self._kp(upos),))):
                    upos, flemma = g, ftext
                    break
        if upos in ("VERB", "AUX"):
            flemma = self._verb_lemma(ftext, flemma)
            if flemma not in self._infs() and flemma != "چاہیے":
                # a noun/adjective Stanza read as a verb (کام, ٹھیک): the dictionary word
                for kp, g in (("noun", "NOUN"), ("adj", "ADJ"), ("adv", "ADV")):
                    if has(ftext, (kp,)):
                        upos, flemma = g, ftext
                        break
                else:
                    n_ = self._noun_base(ftext, has)
                    if n_:
                        upos, flemma = "NOUN", n_           # تالے: تالا, not تالنا
                    elif [v for v in self._forms_of(ftext, ("verb",)) if v in self._infs()]:
                        flemma = [v for v in self._forms_of(ftext, ("verb",)) if v in self._infs()][0]
                    elif not any(r[6] for r in info.get(ftext, [])) and ftext + "نا" != flemma:
                        upos, flemma = "PROPN", ftext       # no word at all (فرح): a name, not فرحنا
        elif upos in ("NOUN", "PROPN", "ADJ", "ADV") and ftext in NUMBERS and ftext not in ("نو", "سو"):
            upos, flemma = "NUM", ftext
        elif upos == "NOUN":
            if ftext.endswith("وں"):
                # -وں plural: the likeliest dictionary noun among Stanza's lemma, the bare stem
                # and the -ا/-ہ stem (چوروں: چور, not چورا; کھانوں: کھانا, not کھان)
                from wordfreq import zipf_frequency
                cands = [c for c in dict.fromkeys((flemma, ftext[:-2], ftext[:-2] + "ا", ftext[:-2] + "ہ"))
                         if has(c, ("noun",))]
                if cands:
                    flemma = max(cands, key=lambda c: (zipf_frequency(c, "ur"), c == flemma))
            if ftext.endswith("وں") and has(ftext[:-2] + "ا", ("adj",)) and not has(ftext[:-2] + "ا", ("noun",)):
                from wordfreq import zipf_frequency   # بڑوں "elders": بڑا, not بڑ "babble"
                if zipf_frequency(ftext[:-2] + "ا", "ur") > zipf_frequency(ftext[:-2], "ur") + 1:
                    return self._alt([ftext, ftext[:-2] + "ا", "ADJ", ms])
            if not has(flemma, ("noun",)) and not has(ftext, ("noun",)) and self._noun_base(ftext, has):
                flemma = self._noun_base(ftext, has)        # عملے -> عملہ (oblique of a -ہ/-ا noun)
            if not has(flemma, ("noun",)):
                c = self._forms_of(ftext, ("noun",))
                if has(ftext, ("noun",)):
                    flemma = ftext
                elif c:
                    flemma = c[0]
        elif upos == "ADJ":
            m = ftext[:-1] + "ا" if ftext[-1:] in ("ی", "ے") else None
            if m and m != flemma and has(m, ("adj",)) and m in self._forms_of(ftext, ("adj",)):
                flemma = m                                  # بری -> برا, not بری "acquitted"
            elif not has(flemma, ("adj", "det")):
                c = self._forms_of(ftext, ("adj", "det"))
                if has(ftext, ("adj",)):
                    flemma = ftext
                elif c:
                    flemma = c[0]
        elif upos == "ADV" and flemma != ftext and has(ftext, ("adv",)):
            flemma = ftext                                  # نیچے "down", not نیچہ "hookah-pipe"
        elif upos == "PROPN" and has(ftext, ("noun", "adj", "adv")) and \
                not any(r[1] == "name" for r in info.get(ftext, [])):
            upos, flemma = ("NOUN" if has(ftext, ("noun",)) else "ADJ" if has(ftext, ("adj",)) else "ADV"), ftext
        elif upos == "NUM" and ftext not in NUMBERS and flemma not in NUMBERS and \
                not re.search(r"\d", ftext) and has(ftext, ("adj", "noun")):
            upos, flemma = ("ADJ" if has(ftext, ("adj",)) else "NOUN"), ftext
        if upos in ("NOUN", "PROPN", "ADJ") and ftext not in NAMES and \
                not any(r[6] for r in info.get(flemma, [])) and not any(r[6] for r in info.get(ftext, [])):
            upos, flemma = self._rescue(ftext, upos, flemma, has)
        return self._alt([ftext, flemma, upos, ms])

    def _alt(self, tok):
        a = self._dict()["alt"].get(tok[1])
        if a and self.group_kpos.get(tok[2]) and a[1] in self.group_kpos[tok[2]]:
            tok[1] = a[0]
        return tok

    def _rescue(self, w, upos, lemma, has):
        """A content token whose reading is no dictionary word: the word it inflects.
        Adjective -ی/-ے/-وں forms (تھوڑی, پیاری, بڑوں -> تھوڑا, پیارا, بڑا), noun plurals
        (مشینوں -> مشین), oblique -ے of -ا/-ہ nouns (بڑھاپے -> بڑھاپا), verb forms Stanza
        read as a noun or name (جاگیں, سوچو -> جاگنا, سوچنا). Unchanged when none fits."""
        if w.endswith("ین") and len(w) > 3 and has(w[:-2], ("noun", "adj")):
            return ("NOUN" if has(w[:-2], ("noun",)) else "ADJ"), w[:-2]   # ماہرین -> ماہر (Arabic plural)
        for end in ("ی", "ے", "وں"):
            if w.endswith(end) and len(w) > len(end) + 1 and has(w[:-len(end)] + "ا", ("adj",)):
                if end != "وں" or not has(w[:-2], ("noun",)):
                    return "ADJ", w[:-len(end)] + "ا"
        for end in ("وں", "ؤں", "یں", "ئیں"):
            if w.endswith(end) and len(w) > len(end) + 1 and has(w[:-len(end)], ("noun",)):
                return "NOUN", w[:-len(end)]
        n_ = self._noun_base(w, has)
        if n_:
            return "NOUN", n_
        infs = self._infs()
        for end in ("ئیں", "یں", "ئے", "و", "ے", "ی", "ا", "تے", "تی", "تا", "نے"):
            if w.endswith(end) and len(w) > len(end) + 1 and w[:-len(end)] + "نا" in infs:
                return "VERB", w[:-len(end)] + "نا"
        # nothing fits: the surface, never a stripped non-word (کامران, not کامر)
        return upos, w

    def fix_sentence(self, toks, row, doc):
        """اس/ان (oblique of یہ and وہ): یہ when the translation says this/these;
        stock names that spell a word are names when the translation has the name."""
        en = (row[3] if row else "") or ""
        this = bool(re.search(r"\b(this|these|here)\b", en, re.I))
        q = en.rstrip().endswith("?") or bool(row and (row[1] or "").rstrip().endswith("؟"))
        for i, t in enumerate(toks):
            # کیا in a question: sentence-initial yes/no particle, or "what" before the copula
            # (کیا ہے؟) -- the perfect of کرنا only when neither holds
            if t[0] == "کیا" and t[2] in ("VERB", "AUX") and q and \
                    (i == 0 or (i + 1 < len(toks) and toks[i + 1][0] in self.COPULA)):
                t[1], t[2] = "کیا", "PRON"
            # homographs the translation decides: اسی "eighty" / "this very", ہوا "wind" /
            # ہونا, سونا "gold" / "to sleep", چینی "sugar" / "Chinese"
            h = HOMOGRAPH_EN.get(t[0])
            if h and en and re.search(h[0], en, re.I) and t[2] != h[1]:
                t[1], t[2] = t[0], h[1]
            # obligation with a dative subject: the infinitive agrees with its object (مجھے توجہ
            # دینی ہے "I must pay attention"), never the homograph adjective/noun دینی "religious"
            # -- but a noun headword (پانی, not پانا) or a word after a modifier (ٹھنڈا پانی) is the noun
            if t[0][-2:] in ("نی", "نا", "نے") and t[2] != "VERB" and len(t[0]) > 3 and \
                    not (i and toks[i - 1][2] in ("ADJ", "DET", "NUM")) and \
                    not (self._has(t[0], ("noun",)) and not self._has(t[0], ("adj",))) and \
                    self._has(t[0][:-1] + "ا", ("verb",)) and i + 1 < len(toks) and \
                    toks[i + 1][0] in self.OBLIG_AFTER and \
                    any(x[0] in DATIVE_PRON or x[0] == "کو" for x in toks[:i]):
                t[1], t[2] = t[0][:-1] + "ا", "VERB"
            # بجے after a number is "o'clock" (پانچ بجے), not بجنا "to ring"
            if t[0] == "بجے" and i and (toks[i - 1][2] == "NUM" or re.search(r"\d", toks[i - 1][0])):
                t[1], t[2] = "بجے", "ADV"
            # سی/سے after an adjective or quantity: the particle سا (چھوٹی سی, بہت سی), never سینا
            if t[0] == "سی" and i and toks[i - 1][2] in ("ADJ", "ADV", "DET", "NUM"):
                t[1], t[2] = "سا", "PART"
            # -ی/-ے form of an -ا adjective that is also a noun (کالی, پوری, سستی): the
            # adjective before a noun (کالی بلی) and, unless the noun is much commoner, as a
            # predicate (بلی کالی ہے); otherwise the tagger's noun stands
            if t[2] == "NOUN" and t[0][-1:] in ("ی", "ے") and self._has(t[0][:-1] + "ا", ("adj",)) and \
                    t[0] in self._forms_of(t[0], ("adj",)) + [t[0][:-1] + "ی", t[0][:-1] + "ے"]:
                nxt = toks[i + 1] if i + 1 < len(toks) else None
                if nxt and nxt[2] == "NOUN" and not self._has(t[0], ("adj",)) and \
                        not (i + 2 < len(toks) and toks[i + 2][0] in POSTPS and nxt[0] in ("کا", "کی", "کے")):
                    t[1], t[2] = t[0][:-1] + "ا", "ADJ"
                elif (nxt and (nxt[0] in self.COPULA or nxt[1] == "ہونا") and i and toks[i - 1][1] != "کا" and
                      toks[i - 1][2] in ("NOUN", "PRON", "PROPN", "ADJ", "ADP", "ADV")) or \
                        sum(x[2] != "PUNCT" for x in toks) == 1:    # or a bare answer option (کالی)
                    from wordfreq import zipf_frequency
                    if zipf_frequency(t[0][:-1] + "ا", "ur") >= zipf_frequency(t[0], "ur") - 0.5:
                        t[1], t[2] = t[0][:-1] + "ا", "ADJ"
            nxt = toks[i + 1] if i + 1 < len(toks) else None
            cv = False
            # a clause with no finite verb ends in one: a clause-final "noun" that is a verb
            # form is that verb (بہت اچھا کھیلا؟, انہیں آرام ملا۔ -- not کھیلا, ملا "mullah")
            if t[2] == "NOUN" and (nxt is None or nxt[0] in ("۔", "؟", "!", "?", ".")) and \
                    i and toks[i - 1][1] != "کا":
                vs = [v for v in self._forms_of(t[0], ("verb",)) if v in self._infs() and v != t[0] + "نا"] + \
                     [t[0][:-len(e)] + "نا" for e in ("ا", "ی", "ے", "یں", "یا", "ئی", "ئے")
                      if t[0].endswith(e) and t[0][:-len(e)] + "نا" in self._infs() and
                      t[0] in verb_forms(t[0][:-len(e)] + "نا")]
                if vs and self._verbless_clause(toks, i):
                    t[1], t[2] = vs[0], "VERB"
            if t[2] == "VERB" and (nxt is None or nxt[2] in ("PUNCT", "CCONJ")) and \
                    i and toks[i - 1][1] != "کا" and self._verbless_clause(toks, i):
                cv = True                               # the clause's verb: no noun rule below
            # a clause-final -یں "noun" with a verb reading is the verb (ایک ہی وقت پر جاگیں،)
            if t[2] == "NOUN" and t[0].endswith("یں") and (nxt is None or nxt[2] in ("PUNCT", "CCONJ")):
                st = t[0][:-3] if t[0].endswith("ئیں") else t[0][:-2]
                if st + "نا" in self._infs():
                    t[1], t[2] = st + "نا", "VERB"
            # a verb reading where only a noun can stand: after an adjective, a genitive
            # or a coordinated noun (نئے جوتے, کپڑے اور جوتے, مرغی کا سالن): the noun
            if t[2] == "VERB" and i and not cv and (toks[i - 1][2] in ("ADJ", "NUM") or toks[i - 1][1] == "کا" or
                                         (toks[i - 1][2] == "CCONJ" and i > 1 and toks[i - 2][2] == "NOUN")):
                from wordfreq import zipf_frequency
                n_ = self._noun_base(t[0], self._has) or (t[0] if self._has(t[0], ("noun",)) else None)
                if toks[i - 1][1] == "کا":
                    n_ = n_ or t[0]                     # nothing but a noun follows a genitive
                elif n_ and zipf_frequency(n_, "ur") <= zipf_frequency(t[1], "ur"):
                    n_ = None                           # اچھا لگا: the verb is the likelier word
                if n_ and (nxt is None or nxt[2] not in ("AUX", "VERB")):
                    t[1], t[2] = n_, "NOUN"
            # a -یں "verb" whose stem is a noun, coordinated with a noun or followed in its
            # clause by the real verb (بسیں اور ایمبولینس, بسیں زیادہ ہونی چاہییں): the plural
            if t[2] == "VERB" and t[0].endswith("یں") and self._has(t[0][:-2], ("noun",)) and \
                    nxt and nxt[2] not in ("VERB", "AUX", "PUNCT"):
                k = i + 1
                while k < len(toks) and toks[k][2] not in ("PUNCT", "CCONJ", "SCONJ", "VERB", "AUX"):
                    k += 1
                if (nxt[2] == "CCONJ" and i + 2 < len(toks) and toks[i + 2][2] == "NOUN") or \
                        (k < len(toks) and toks[k][2] in ("VERB", "AUX") and k > i + 1):
                    t[1], t[2] = t[0][:-2], "NOUN"
            # -ے of an -ا adjective read as an adverb before a noun that is not the verb's
            # object (پہلے دن وہ ..., not پہلے کھانا کھاؤ): the adjective
            if t[2] == "ADV" and t[0].endswith("ے") and self._has(t[0][:-1] + "ا", ("adj",)) and \
                    nxt and nxt[2] == "NOUN" and not (i + 2 < len(toks) and toks[i + 2][2] in ("VERB", "AUX")):
                t[1], t[2] = t[0][:-1] + "ا", "ADJ"
            # multi-word place names are one name: اسلام آباد (Islamabad), not آباد; نیو یارک
            if t[0] in PLACE_TAILS and i and re.search(r"\b[A-Z]\w*" + PLACE_TAILS[t[0]] + r"\b", en):
                toks[i - 1][1], toks[i - 1][2] = toks[i - 1][0], "PROPN"
                t[1], t[2] = t[0], "PROPN"
            if t[0] == "نیو" and nxt is not None and re.search(r"\bNew [A-Z]", en):
                t[1], t[2] = t[0], "PROPN"
                nxt[1], nxt[2] = nxt[0], "PROPN"
            nxt0 = toks[i + 1] if i + 1 < len(toks) else None
            # an English loan spelled like a verb stem, when the translation has the word
            if t[0] in LOAN_EN and t[2] in ("VERB", "AUX", "NOUN", "ADJ", "ADV") and re.search(LOAN_EN[t[0]], en, re.I):
                t[1], t[2] = t[0], "ADJ" if t[0] == "لیٹ" else "NOUN"
            elif t[0] in LOAN_EN and t[2] == "ADP" and re.search(LOAN_EN[t[0]], en, re.I) and \
                    nxt0 and fold(nxt0[1]) in ("ہونا", "کرنا"):
                t[2] = "X"          # امتحان میں پاس ہونا "to pass": no pack sense (never پاس "near")
            if t[0] in LOAN_OTHER_SENSE and re.search(LOAN_OTHER_SENSE[t[0]][0], en, re.I) and \
                    not re.search(LOAN_OTHER_SENSE[t[0]][1], en, re.I):
                t[2] = "X"
            # a two-word English loan (فٹ بال football, والی بال): one unit, never "foot" + "ball"
            if nxt0 and (t[0], nxt0[0]) in LOAN_PAIRS:
                t[2] = nxt0[2] = "X"
            # کی read as کرنا after a noun that forms no کرنا light verb, with a verb right
            # after it, is the genitive (بڑی زور کی لگی ہے "you got hit hard"), not کرنا
            if t[0] == "کی" and t[1] == "کرنا" and i and toks[i - 1][2] == "NOUN" and \
                    fold(toks[i - 1][0]) + " کرنا" not in LIGHT_VERBS and fold(toks[i - 1][1]) + " کرنا" not in LIGHT_VERBS and \
                    nxt0 and nxt0[2] in ("VERB", "AUX") and nxt0[1] not in ("ہونا", "جانا", "دینا", "لینا", "سکنا", "چکنا", "رہنا"):
                t[1], t[2] = "کا", "ADP"
            # after an oblique interrogative/relative pronoun کی/کے/کا is always the genitive
            # (یہ تحریر کس کی ہے؟ "whose"), never کرنا
            if t[0] in ("کی", "کے", "کا") and t[1] != "کا" and i and toks[i - 1][0] in ("کس", "جس", "کن", "جن"):
                t[1], t[2] = "کا", "ADP"
            # a light-verb noun + کی/کیا/کیے/کیں after an ergative نے, with no later finite
            # verb in the clause, is کرنا (ڈاکٹر نے ہر ممکن کوشش کی مریض کو بچانے ...), not کا
            erg0 = any(x[0] == "نے" for x in toks[:i])
            if t[0] in ("کی", "کیا", "کیے", "کیں") and t[1] != "کرنا" and i and toks[i - 1][2] == "NOUN" and \
                    erg0 and (fold(toks[i - 1][1]) + " کرنا" in LIGHT_VERBS or fold(toks[i - 1][0]) + " کرنا" in LIGHT_VERBS):
                later = []
                for x in toks[i + 1:]:
                    if x[2] == "PUNCT":
                        break
                    later.append(x)
                if not any((x[2] in ("VERB", "AUX") and not x[0].endswith(("نے", "نا")) and x[1] != "ہونا")
                           or x[0] in ("کی", "کیا", "کیے", "کیں") for x in later):
                    t[1], t[2] = "کرنا", "VERB"
            # کی before the copula after a noun that forms no کرنا compound is the genitive
            # predicate (یہ میز لکڑی کی ہے), not کرنا (بات کی ہے stays کرنا)
            erg = any(x[0] == "نے" for x in toks[:i]) and not any(x[2] == "VERB" for x in toks[:i - 1])
            if t[0] == "کی" and t[2] in ("VERB", "AUX") and i and toks[i - 1][2] == "NOUN" and not erg and \
                    nxt and nxt[0] in self.COPULA and fold(toks[i - 1][1]) + " کرنا" not in LIGHT_VERBS and \
                    not self._has(fold(toks[i - 1][1]) + " کرنا", ("verb",)):
                t[1], t[2] = "کا", "ADP"
            # a finite verb never takes a postposition: -ے before one is an oblique noun
            # (کرائے پر -> کرایہ, not کرانا); the oblique infinitive -نے is left alone
            if t[2] == "VERB" and i + 1 < len(toks) and toks[i + 1][0] in POSTPS and \
                    t[0].endswith("ے") and not t[0].endswith("نے"):
                n_ = self._noun_base(t[0], self._has)
                if n_:
                    t[1], t[2] = n_, "NOUN"
            # link traps (QA 2026-09-26) ---------------------------------------------
            # imperative/future دو of دینا, not "two": at a clause end (خون دو، / دھیان دو۔)
            # or before نا / the future گے (دو گے)
            if t[0] == "دو" and t[2] == "NUM" and i and toks[i - 1][2] != "NUM" and \
                    toks[i - 1][0] not in ("ایک", "ان", "یہ", "وہ", "ہم", "تم") and \
                    (nxt is None or nxt[0] in ("۔", "؟", "!", "،", "نا", "گے", "گی", "گا")):
                t[1], t[2] = "دینا", "VERB"
            # بس: the bus after a determiner/adjective/genitive or before a postposition or
            # stop/driver; otherwise the adverb "just, only; enough" (بس تھوڑا، بس آتی ہوں گی)
            if t[0] == "بس":
                prv = toks[i - 1] if i else None
                bus = (nxt is not None and (nxt[0] in POSTPS or nxt[0] in ("اسٹاپ", "سٹاپ", "ڈرائیور", "اڈے", "اڈا"))) or \
                      (prv is not None and (prv[2] in ("ADJ", "NUM", "DET") or prv[0] in ("کی", "ایک", "کوئی")))
                t[1], t[2] = ("بس", "NOUN") if bus else ("بس", "ADV")
            # a causative stem (پکا, لگا, اٹھا) before a progressive/modal/vector auxiliary or
            # the conjunctive کر is the -انا verb (پکا رہی ہیں -> پکانا, not پکنا); رہ- only as the
            # progressive, never before the future گا (کھلا رہے گا "will stay open" is کھلنا)
            nxt2 = toks[i + 2][0] if i + 2 < len(toks) else ""
            if t[2] in ("VERB", "NOUN", "ADJ") and t[0].endswith("ا") and t[0] + "نا" in self._infs() and \
                    t[1] != t[0] + "نا" and nxt is not None and \
                    not (nxt[0].startswith("رہ") and nxt2 in ("گا", "گی", "گے")) and \
                    re.fullmatch("رہ(?:ا|ی|ے|یں)|سک(?:تا|تی|تے|ا|ی|ے|یں|وں)|چک(?:ا|ی|ے|یں)|کر|کے|د(?:و|یں|یا|ی|ے|یجیے|یجئے)|ل(?:و|یں|یا|ی|ے|یجیے)",
                                 nxt[0]):
                t[1], t[2] = t[0] + "نا", "VERB"
            # a bare verb stem before the copula or ملنا is the noun of that spelling
            # (کپڑوں پر چھوٹ ہے, فیس میں چھوٹ ملی: the discount, not چھوٹنا)
            if t[2] == "VERB" and t[1] == t[0] + "نا" and nxt is not None and \
                    not (t[0][-1:] in ("ا", "ی", "ے") and t[0][:-1] + "نا" in self._infs()) and \
                    (nxt[0] in self.COPULA or re.fullmatch("مل(?:ا|ی|ے|یں|تا|تی|تے|ے گا|ے گی)", nxt[0])) and \
                    self._has(t[0], ("noun",)):
                t[1], t[2] = t[0], "NOUN"
            prv = toks[i - 1] if i else None
            # a verb reading after a quantifier, number or possessive is the noun form
            # (کتنے بچے, میرے بچے, آپ کے بچے: بچہ, not بچنا)
            if t[2] in ("VERB", "AUX") and prv is not None and \
                    (prv[2] in ("DET", "NUM") or prv[0] in QUANT_BEFORE_NOUN or
                     (prv[0] in ("کا", "کی", "کے") and i > 1 and toks[i - 2][2] in ("PRON", "NOUN", "PROPN"))):
                nl = self._noun_of_form(t[0])
                if nl:
                    t[1], t[2] = nl, "NOUN"
            # a modal form (سکے, سکا, چکے) needs a verb stem before it; after a postposition,
            # determiner, number or adjective it is the noun of that spelling (مٹھی میں سکے: coins)
            if t[1] in ("سکنا", "چکنا") and prv is not None and prv[2] in ("ADP", "DET", "NUM", "ADJ"):
                nl = self._noun_of_form(t[0])
                if nl:
                    t[1], t[2] = nl, "NOUN"
            # the second part of a بے compound (بے بسی, بے چینی) is not a word of its own
            if prv is not None and prv[0] == "بے" and t[2] in ("VERB", "AUX", "NOUN", "ADJ"):
                t[2] = "X"
            # -وں at a clause end on a verb stem is the 1sg subjunctive (میں پہنچوں), not
            # the oblique plural of a noun of that spelling
            if t[0].endswith("وں") and t[2] != "VERB" and t[0][:-2] + "نا" in self._infs() and \
                    (nxt is None or nxt[2] == "PUNCT" or nxt[0] in ("کہ", "تو", "گا", "گی")) and \
                    not (prv is not None and prv[2] in ("DET", "NUM", "ADJ")):
                t[1], t[2] = t[0][:-2] + "نا", "VERB"
            # a predicate noun that is also an adjective, right after its subject pronoun
            # or an intensifier, is the adjective (یہ مشکل ہے, یہ بہت مشکل ہے: difficult);
            # after a postposition it stays the noun (آنکھوں میں اداسی تھی: sadness)
            if t[2] == "NOUN" and nxt is not None and nxt[0] in self.COPULA and prv is not None and \
                    (prv[0] in PRED_SUBJ or prv[0] in ("بہت", "کافی", "زیادہ", "بالکل")) and \
                    self._has(t[0], ("adj",)):
                t[1], t[2] = t[0], "ADJ"
            if t[0] in PROX_OBL and t[1] == "وہ" and this:
                t[1] = "یہ"
            if t[0] in NAME_EN and re.search(r"\b" + NAME_EN[t[0]] + r"\b", en):
                t[1], t[2] = t[0], "PROPN"
        # agreement scope for the shared کا/کی/کے gender check (core det_gender): a
        # possessive or genitive agrees with its head noun, so its gender feature goes
        # when the next noun is itself a genitive modifier (ہمارا ریاضی کا ٹیسٹ) or the
        # postposition is not کا/کی/کے (کے دوران بارش)
        for j, t in enumerate(toks):
            if t[2] not in ("DET", "ADP") or "Gender=" not in (t[3] or ""):
                continue
            k = j + 1
            while k < len(toks) and toks[k][2] == "ADJ":
                k += 1
            if (t[2] == "ADP" and t[0] not in ("کا", "کی", "کے")) or \
                    (k + 1 < len(toks) and toks[k + 1][0] in ("کا", "کی", "کے")):
                t[3] = re.sub(r"\|?Gender=\w+", "", t[3]).lstrip("|")
        return toks

