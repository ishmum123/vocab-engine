        t = re.sub(f"(?<![{LET}])کیل(?:ئ|ی)ے(?![{LET}])", "کے لیے", t)
        d = self._dict()

        def word(w):            # the fused spelling is itself a word or an inflection of one (پیلی, آلو)
            w = fold(w)
            return w in d["info"] or w in d["forms"] or any(
                w.endswith(e) and w[:-len(e)] + b in d["info"] for e in ("ی", "ے", "یں", "وں") for b in ("ا", "ہ", ""))
        t = FUSED_RE.sub(lambda m: m.group(0) if word(m.group(0)) else " ".join(g for g in m.groups() if g), t)
        return t

